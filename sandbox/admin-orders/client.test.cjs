const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {stripTypeScriptTypes}=require('node:module');
const source=stripTypeScriptTypes(fs.readFileSync(__dirname+'/client.ts','utf8').replace(/export /g,''));
let requests=[];
const ctx={AbortSignal,fetch:async(url,init)=>{
 assert.ok(url.startsWith('https://qqehtphbpypcmxliaiqd.supabase.co/'));
 const body=JSON.parse(init.body);requests.push({url,body});
 if(url.includes('/auth/'))return Response.json({access_token:'dummy-test-token'});
 if(body.action==='list')return Response.json({ok:true,orders:[{id:'synthetic'}]});
 if(body.action==='audit')return Response.json({ok:true,entries:[{id:'evidence'}]});
 if(body.action==='items')return Response.json({ok:true,items:[]});
 if(body.action==='history')return Response.json({ok:true});
 return Response.json({ok:false,error:'refund_detected'},{status:409});
}};
vm.createContext(ctx);vm.runInContext(source+'\nthis.api={signIn,signOut,call,supabase};',ctx);
(async()=>{
 const {api}=ctx;
 assert.ok((await api.supabase.rpc('current_admin_country')).error,'auth required');
 assert.equal(requests.length,0);
 await api.signIn('test@example.invalid','dummy');
 assert.equal((await api.supabase.rpc('current_admin_country')).data,'IN');
 assert.equal((await api.supabase.from('orders').select('*').eq('country_code','IN').order('created_at')).data.length,1);
 let count=requests.length;
 assert.ok((await api.supabase.from('orders').update({status:'shipped'}).eq('id','synthetic')).error);
 assert.ok((await api.supabase.from('orders').select('*').eq('country_code','BD')).error);
 assert.ok((await api.supabase.from('admin_users').select('*')).error);
 assert.ok((await api.supabase.rpc('collect_cod_due_atomic')).error);
 assert.ok((await api.call('arbitrary-function',{})).error);
 assert.equal(requests.length,count,'forbidden operations never transmit');
 assert.equal((await api.supabase.from('order_items').select('*').eq('order_id','synthetic')).data.length,0);
 assert.equal((await api.supabase.rpc('get_order_payment_audit',{p_order_id:'synthetic'})).data[0].id,'evidence');
 assert.equal((await api.supabase.from('order_status_history').insert({order_id:'synthetic',status:'shipped',note:'test'})).data.ok,true);
 const blocked=await api.supabase.functions.invoke('cashfree-verify-dispatch',{body:{orderId:'synthetic',status:'shipped'}});
 assert.equal(blocked.data.error,'refund_detected');assert.ok(blocked.error);
 api.signOut();count=requests.length;
 assert.equal((await api.supabase.auth.getSession()).data.session,null);
 assert.ok((await api.supabase.functions.invoke('cashfree-verify-dispatch',{body:{}})).error);
 assert.equal(requests.length,count);
 console.log('PASS Sandbox client: session, original-page reads/audit/history, direct-write/BD/RPC/function isolation, error handling and signout');
})().catch(e=>{console.error(e);process.exitCode=1});
