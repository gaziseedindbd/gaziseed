type LangContextType = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (bn: string, en: string) => string;
  tDb: (text: string) => string;
};

const LangContext = createContext<LangContextType>({
  lang: 'en',
  setLang: () => {},
  t: (_bn, en) => en,
  tDb: (text) => text,
});

const LANG_KEY = 'gazi_lang';
const getCountryLangKey = (country: 'BD' | 'IN') => `${LANG_KEY}_${country}`;
const isLang = (value: string | null): value is Lang => value === 'bn' || value === 'en' || value === 'hi';

export function LanguageProvider({
  children,
  defaultCountry = 'BD',
}: {
  children: ReactNode;
  defaultCountry?: 'BD' | 'IN';
}) {
  const [lang, setLangState] = useState<Lang>(defaultCountry === 'IN' ? 'en' : 'bn');

  useEffect(() => {
    const saved = localStorage.getItem(getCountryLangKey(defaultCountry));
    if (isLang(saved) && !(defaultCountry === 'BD' && saved === 'hi')) {
      setLangState(saved);
    } else {
      setLangState(defaultCountry === 'IN' ? 'en' : 'bn');
    }
  }, [defaultCountry]);

  useEffect(() => {
    document.documentElement.lang = lang === 'hi' ? 'hi' : lang === 'bn' ? 'bn' : 'en';
  }, [lang]);

  const setLang = (next: Lang) => {
    const safeLang = defaultCountry === 'BD' && next === 'hi' ? 'bn' : next;
    setLangState(safeLang);
    localStorage.setItem(LANG_KEY, safeLang);
    localStorage.setItem(getCountryLangKey(defaultCountry), safeLang);
  };

  const t = (bn: string, en: string) => {
    if (lang === 'bn') return bn;
    if (lang === 'hi') return HINDI_TRANSLATIONS[bn] || en;
    return en;
  };

  const tDb = (text: string) => {
    if (!text) return text;
    const trimmed = text.trim();

    if (trimmed.startsWith('{') && trimmed.endsWith('}')) {
      try {
        const parsed = JSON.parse(trimmed);
        if (parsed && typeof parsed === 'object') {
          if (lang === 'en' && parsed.en) return parsed.en as string;
          if (lang === 'hi' && parsed.hi) return parsed.hi as string;
          if (lang === 'hi' && parsed.bn && HINDI_DB_TRANSLATIONS[parsed.bn]) return HINDI_DB_TRANSLATIONS[parsed.bn];
          if (lang === 'bn' && parsed.bn) return parsed.bn as string;
        }
      } catch {
        // Fall through to regular text handling.
      }
    }

    if (lang === 'hi') return HINDI_DB_TRANSLATIONS[trimmed] || HINDI_TRANSLATIONS[trimmed] || DB_TRANSLATIONS[trimmed] || trimmed;
    if (lang === 'en') return DB_TRANSLATIONS[trimmed] || trimmed;
    return trimmed;
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t, tDb }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
